#!/usr/bin/env node
// ─────────────────────────────────────────────────────────────────────────────
//  build-pose-manifest.mjs — make pose media auto-register from disk
//
//  THE PROBLEM THIS SOLVES
//  -----------------------
//  Pose videos were registered in a hand-maintained POSE_VIDEOS map in
//  PoseFigure.jsx. Drop a new {poseKey}.mp4 into public/poses/ but forget to
//  add the map entry, and the video silently never appears in-app. That had
//  already happened to 5 videos.
//
//  Fix: this script scans public/poses/ and writes src/data/poseManifest.js —
//  the single source of truth for which media files actually exist. PoseFigure
//  reads the manifest instead of a hand-kept list. Wired to npm predev +
//  prebuild so it regenerates on every `npm run dev` / `npm run build` — a
//  newly-dropped file appears with zero code edits.
//
//  WHAT IT EXPORTS  (src/data/poseManifest.js)
//    VIDEO_FILES — { [lowercasedBasename]: actualFilename }   e.g. { cobra: 'Cobra.mp4' }
//    IMAGE_FILES — { [lowercasedBasename]: actualFilename }
//  Lowercased keys so lookups are case-insensitive; values keep real casing
//  for the URL (the filesystem + some hosts are case-sensitive).
//
//  ALIASES (poseKey → filename indirections, e.g. forwardBend →
//  paschimottanasana) stay in PoseFigure.jsx — they're code-level naming
//  decisions, not facts about the disk.
// ─────────────────────────────────────────────────────────────────────────────

import { readdirSync, writeFileSync, mkdirSync } from 'node:fs'
import { dirname, join } from 'node:path'
import { fileURLToPath } from 'node:url'

const __dirname = dirname(fileURLToPath(import.meta.url))
const REPO   = join(__dirname, '..')
const POSES  = join(REPO, 'public', 'poses')
const OUT    = join(REPO, 'src', 'data', 'poseManifest.js')

function collect(ext) {
  let files
  try {
    files = readdirSync(POSES)
  } catch {
    return {}
  }
  const map = {}
  for (const f of files) {
    if (!f.toLowerCase().endsWith(ext)) continue
    const base = f.slice(0, -ext.length)        // strip extension
    map[base.toLowerCase()] = f                  // key: lowercased base, value: real filename
  }
  // Stable key order for clean diffs.
  return Object.fromEntries(Object.entries(map).sort(([a], [b]) => a.localeCompare(b)))
}

const videos = collect('.mp4')
const images = collect('.png')

const body = `// AUTO-GENERATED by scripts/build-pose-manifest.mjs — DO NOT EDIT BY HAND.
// Regenerated on every \`npm run dev\` / \`npm run build\`. To add a pose video
// or image, just drop the file into public/poses/ — it registers automatically.
//
// Keys are lowercased basenames (case-insensitive lookup); values keep the
// real on-disk filename casing for the URL.

export const VIDEO_FILES = ${JSON.stringify(videos, null, 2)}

export const IMAGE_FILES = ${JSON.stringify(images, null, 2)}
`

mkdirSync(dirname(OUT), { recursive: true })
writeFileSync(OUT, body)
console.log(`▸ pose manifest: ${Object.keys(images).length} images, ${Object.keys(videos).length} videos → src/data/poseManifest.js`)
