#!/usr/bin/env node
// ─────────────────────────────────────────────────────────────────────────────
//  build-pose-manifest.mjs — single source of truth for pose media
//
//  Writes src/data/poseManifest.js (committed) describing which pose media
//  exist, so PoseFigure resolves them without a hand-kept map. Regenerated on
//  every `npm run dev` / `npm run build` (predev/prebuild) and by
//  `npm run poses`.
//
//  IMAGES — bundled. Live in public/poses/*.png, committed, shipped in the
//  app binary (small, needed offline). Scanned fresh from disk every run.
//
//  VIDEOS — NOT bundled. Hosted in Supabase Storage (public `poses` bucket)
//  and streamed at runtime, so they never bloat the APK/IPA past store
//  limits. Local masters live in media/pose-videos/ (gitignored staging dir,
//  the dev's working copies). `npm run poses:upload` pushes them to Storage.
//
//  PRESERVE-ON-ABSENT: video entries are regenerated from media/pose-videos/
//  ONLY when that dir has files. On a fresh clone / CI (no local videos) the
//  existing committed VIDEO_FILES are preserved — otherwise a build there
//  would wipe the list and the videos would vanish from the app.
// ─────────────────────────────────────────────────────────────────────────────

import { readdirSync, writeFileSync, mkdirSync, existsSync, readFileSync } from 'node:fs'
import { dirname, join } from 'node:path'
import { fileURLToPath } from 'node:url'

const __dirname  = dirname(fileURLToPath(import.meta.url))
const REPO       = join(__dirname, '..')
const IMG_DIR    = join(REPO, 'public', 'poses')      // bundled stills
const VID_DIR    = join(REPO, 'media', 'pose-videos') // local masters (gitignored)
const OUT        = join(REPO, 'src', 'data', 'poseManifest.js')

// Scan a dir for files of one extension → { lowercasedBasename: actualFilename }.
function collect(dir, ext) {
  if (!existsSync(dir)) return {}
  const map = {}
  for (const f of readdirSync(dir)) {
    if (!f.toLowerCase().endsWith(ext)) continue
    map[f.slice(0, -ext.length).toLowerCase()] = f
  }
  return Object.fromEntries(Object.entries(map).sort(([a], [b]) => a.localeCompare(b)))
}

// Read the VIDEO_FILES already committed in the manifest, so we can preserve
// them when no local video masters are present.
function existingVideoFiles() {
  try {
    const txt = readFileSync(OUT, 'utf8')
    const m = txt.match(/export const VIDEO_FILES = (\{[\s\S]*?\})\n/)
    return m ? JSON.parse(m[1]) : {}
  } catch {
    return {}
  }
}

const images = collect(IMG_DIR, '.png')

const localVideos = collect(VID_DIR, '.mp4')
const videos = Object.keys(localVideos).length > 0 ? localVideos : existingVideoFiles()
const videoSource = Object.keys(localVideos).length > 0 ? 'media/pose-videos' : 'preserved (no local masters)'

const body = `// AUTO-GENERATED by scripts/build-pose-manifest.mjs — DO NOT EDIT BY HAND.
// Regenerated on every \`npm run dev\` / \`npm run build\`.
//
// IMAGES: public/poses/*.png — bundled, scanned from disk.
// VIDEOS: Supabase Storage (public 'poses' bucket) — listed here from the
// local masters in media/pose-videos/, uploaded via \`npm run poses:upload\`.
// Drop a {poseKey}.png into public/poses/ or {poseKey}.mp4 into
// media/pose-videos/ and it registers automatically on the next build.
//
// Keys are lowercased basenames (case-insensitive lookup); values keep the
// real filename casing for the URL.

export const VIDEO_FILES = ${JSON.stringify(videos, null, 2)}

export const IMAGE_FILES = ${JSON.stringify(images, null, 2)}
`

mkdirSync(dirname(OUT), { recursive: true })
writeFileSync(OUT, body)
console.log(`▸ pose manifest: ${Object.keys(images).length} images (public/poses), ${Object.keys(videos).length} videos [${videoSource}]`)
