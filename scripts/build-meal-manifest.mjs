#!/usr/bin/env node
// ─────────────────────────────────────────────────────────────────────────────
//  build-meal-manifest.mjs — single source of truth for meal-idea imagery.
//
//  Writes src/data/mealManifest.js (committed) mapping meal-template ids to the
//  bundled illustration that exists for them, so MealIdeaCard resolves a photo
//  without a hand-kept map. Regenerated on every `npm run dev` / `npm run build`
//  (predev/prebuild) and by `npm run meals:manifest`.
//
//  IMAGES — bundled. Live in public/meals/*.webp (preferred) or *.png,
//  committed, shipped in the app binary. Small, and needed offline: a meal
//  card that can't reach the network must still show its dish. Scanned fresh
//  from disk every run. Drop a `{mealId}.webp` into public/meals/ and it
//  registers automatically on the next build — same flow as poses.
//
//  Filenames are the template `id` (e.g. kitchari.webp). Keys are the
//  lowercased basename for case-insensitive lookup; values keep the real
//  filename casing for the URL.
// ─────────────────────────────────────────────────────────────────────────────

import { readdirSync, writeFileSync, mkdirSync, existsSync } from 'node:fs'
import { dirname, join } from 'node:path'
import { fileURLToPath } from 'node:url'

const __dirname = dirname(fileURLToPath(import.meta.url))
const REPO      = join(__dirname, '..')
const IMG_DIR   = join(REPO, 'public', 'meals')
const OUT       = join(REPO, 'src', 'data', 'mealManifest.js')

// Scan for images of one extension → { lowercasedBasename: actualFilename }.
function collect(dir, ext) {
  if (!existsSync(dir)) return {}
  const map = {}
  for (const f of readdirSync(dir)) {
    if (!f.toLowerCase().endsWith(ext)) continue
    map[f.slice(0, -ext.length).toLowerCase()] = f
  }
  return map
}

// Prefer WebP over PNG when a dish has both, so a freshly-dropped PNG renders
// and swaps to WebP automatically once converted.
function collectImages(dir) {
  const merged = { ...collect(dir, '.png'), ...collect(dir, '.webp') } // webp wins
  return Object.fromEntries(Object.entries(merged).sort(([a], [b]) => a.localeCompare(b)))
}

const files = collectImages(IMG_DIR)

const banner = `// AUTO-GENERATED by scripts/build-meal-manifest.mjs — DO NOT EDIT BY HAND.
// Regenerated on every \`npm run dev\` / \`npm run build\`.
//
// Bundled meal illustrations: public/meals/*.webp (or *.png), scanned from
// disk. Keys are lowercased template ids; values keep the real filename.
// Drop a {mealId}.webp into public/meals/ and it registers on the next build.
`

const body = `export const MEAL_IMAGE_FILES = ${JSON.stringify(files, null, 2)}\n`

mkdirSync(dirname(OUT), { recursive: true })
writeFileSync(OUT, `${banner}\n${body}`)

console.log(`[meals] manifest: ${Object.keys(files).length} image(s) → src/data/mealManifest.js`)
